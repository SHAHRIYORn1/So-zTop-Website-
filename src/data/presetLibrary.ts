// Helper to convert preset topic into a WordSet
export function createWordSetFromPreset(
  topic: PresetTopic,
  targetLang: 'en' | 'ru' | 'de' = 'en'
) {
  // lang indices: uz=0, en=1, ru=2, de=3
  const langIndexMap: Record<string, number> = {
    uz: 0,
    en: 1,
    ru: 2,
    de: 3,
  };

  const trIdx = langIndexMap[targetLang] ?? 1;

  const words = topic.rawWords.map((line, idx) => {
    const parts = line.split('|');
    const uzWord = parts[0]?.trim() || '';
    const foreignWord = parts[trIdx]?.trim() || parts[1]?.trim() || '';

    // If studying English/Russian/German, foreignWord is the prompt, uzWord is the translation
    return {
      id: `w-${topic.id}-${idx}`,
      w: foreignWord,
      tr: uzWord,
      lg: targetLang,
    };
  });

  return {
    id: `preset-${topic.id}-${Date.now()}`,
    name: `${topic.icon} ${topic.name}`,
    src: targetLang,
    to: 'uz',
    words,
  };
}
